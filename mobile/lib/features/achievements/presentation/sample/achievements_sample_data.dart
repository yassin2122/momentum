enum Rarity {
  common('Common'),
  uncommon('Uncommon'),
  rare('Rare'),
  epic('Epic'),
  legendary('Legendary'),
  mythic('Mythic');

  const Rarity(this.label);
  final String label;

  RarityPalette get palette => switch (this) {
        Rarity.common => AchievementPalette.common,
        Rarity.uncommon => AchievementPalette.uncommon,
        Rarity.rare => AchievementPalette.rare,
        Rarity.epic => AchievementPalette.epic,
        Rarity.legendary => AchievementPalette.legendary,
        Rarity.mythic => AchievementPalette.mythic,
      };
}

enum AchievementCategory {
  training('Training'),
  consistency('Consistency'),
  strength('Strength'),
  skills('Skills'),
  xp('XP & Levels');

  const AchievementCategory(this.label);
  final String label;
}

enum AchievementState { locked, inProgress, unlocked, isNew }

final class Achievement {
  const Achievement({
    required this.id,
    required this.slug,
    required this.title,
    required this.category,
    required this.rarity,
    required this.state,
    required this.progress,
    required this.description,
    required this.requirement,
    this.progressLabel,
    this.earnedOn,
  });

  final int id;

  /// Glyph key in [achievementGlyphs].
  final String slug;
  final String title;
  final AchievementCategory category;
  final Rarity rarity;
  final AchievementState state;

  /// 0–1.
  final double progress;
  final String? progressLabel;
  final DateTime? earnedOn;
  final String description;
  final String requirement;

  bool get isEarned =>
      state == AchievementState.unlocked || state == AchievementState.isNew;
}

